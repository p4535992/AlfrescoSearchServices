package org.alfresco.indexing.consistency;

import java.util.List;

public class ConsistencyPage<T>
{
    private final List<T> content;
    private final int page;
    private final int size;
    private final long totalElements;

    public ConsistencyPage(List<T> content, int page, int size, long totalElements)
    {
        this.content = content;
        this.page = page;
        this.size = size;
        this.totalElements = totalElements;
    }

    public List<T> getContent() { return content; }
    public int getPage() { return page; }
    public int getSize() { return size; }
    public long getTotalElements() { return totalElements; }
    public int getTotalPages() { return size == 0 ? 0 : (int) Math.ceil((double) totalElements / size); }
}
